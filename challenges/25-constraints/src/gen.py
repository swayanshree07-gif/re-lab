#!/usr/bin/env python3
"""Generate src/rules.h (spoiler!). Adds random byte rules until the
password is the unique solution (checked with the solver's fallback search).
Usage: python3 src/gen.py > src/rules.h"""
import os, random, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from solve import fallback_solve, evaluate, N  # noqa: E402

PW = b"c0nstr41nt_g4m3!"
assert len(PW) == N
rng = random.Random(2511)
rules = []


def connected(rules):
    seen, todo = {0}, [0]
    while todo:
        v = todo.pop()
        for op, a, b, _ in rules:
            if op < 4 and v in (a, b):
                w = b if v == a else a
                if w not in seen:
                    seen.add(w); todo.append(w)
    return len(seen) == N


while True:
    op = rng.randrange(6)
    a, b = rng.sample(range(N), 2)
    if op == 4 and PW[a] >= PW[b]:
        a, b = b, a
    if op == 4 and PW[a] == PW[b]:
        continue
    if op == 5:
        b = rng.randrange(8)
    r = (op, a, b, 0)
    r = (op, a, b, evaluate(r, PW))
    rules.append(r)
    if len(rules) >= 24 and connected(rules):
        sols = fallback_solve(rules, limit=2)
        if len(sols) == 1:
            break
assert fallback_solve(rules, limit=2) == [PW]
print("/* generated by src/gen.py: do not edit */")
print(f"#define NRULES {len(rules)}")
print("static const struct rule rules[NRULES] = {")
for r in rules:
    print("    {%d, %d, %d, %d}," % r)
print("};")
