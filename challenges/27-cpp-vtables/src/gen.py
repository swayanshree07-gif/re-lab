#!/usr/bin/env python3
"""Writes params.h for 27-cpp-vtables (spoiler!). Deterministic (seeded)."""
import os, random, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from model import fwd, inv

PW = b"v1rtu4l_d1sp4tch_ftw"  # 20 chars = 5 stages x 4
rng = random.Random(27)
kinds = [3, 0, 2, 1, 0]  # every class used, Rot twice (shared vtable)
rows = []
for s, k in enumerate(kinds):
    a = rng.randrange(1, 256) | (1 if k == 3 else 0)
    b = rng.randrange(256)
    chunk = list(PW[4 * s:4 * s + 4])
    t = fwd(k, a, b, chunk)
    assert inv(k, a, b, t) == chunk
    rows.append((k, a, b, t))
with open(os.path.join(HERE, "params.h"), "w") as f:
    f.write("/* generated by gen.py */\n#define PW_LEN %d\n#define N_STAGES %d\n" % (len(PW), len(rows)))
    f.write("struct StageParams { unsigned char kind, a, b, target[4]; };\n")
    f.write("extern const StageParams stage_params[N_STAGES];\n")
    f.write("const StageParams stage_params[N_STAGES] = {\n")
    for k, a, b, t in rows:
        f.write("    {%d, 0x%02x, 0x%02x, {%s}},\n" % (k, a, b, ", ".join("0x%02x" % x for x in t)))
    f.write("};\n")
with open(os.path.join(HERE, "SPOILERS"), "w") as f:
    f.write(PW.decode() + "\n")
