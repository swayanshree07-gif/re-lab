#!/usr/bin/env python3
"""Spoiler: generates bytecode.h for 19-vm-check. Run: python3 gen.py > bytecode.h

Register VM program: length must be 16; loop i=0..15:
  c = in[i]; t = rol8((c ^ h) + i, 3); err |= t ^ data[i]; h = h*7 + c   (h0 = 0x37)
success iff err == 0.
"""
PW = b"r3g1st3r_l00p3d!"
MOVI, MOV, LDI, LDM, ADD, SUB, XOR, MUL, ROL, ADDI, OR, CMP, JMP, JZ, JNZ, LEN, HALT = (
    0x10, 0x11, 0x12, 0x13, 0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x30, 0x31, 0x32, 0x33, 0x40, 0xFF)
H0, MULT, ROT = 0x37, 7, 3

def rol8(x, n): return ((x << n) | (x >> (8 - n))) & 0xFF

data, h = [], H0
for i, c in enumerate(PW):
    data.append(rol8(((c ^ h) + i) & 0xFF, ROT)); h = (h * MULT + c) & 0xFF

def r(a, b): return (a << 4) | b          # two register operands packed in one byte
code = [LEN, 0, MOVI, 1, len(PW), CMP, r(0, 1), JNZ, None,
        MOVI, 2, 0, MOVI, 3, H0, MOVI, 7, 0]
loop = len(code)
code += [LDI, r(4, 2),            # r4 = in[r2]
         MOV, r(5, 4), XOR, r(5, 3), ADD, r(5, 2), ROL, 5, ROT,
         MOV, r(6, 2), LDM, r(6, 6),  # r6 = data[r2]
         XOR, r(6, 5), OR, r(7, 6),
         MOVI, 6, MULT, MUL, r(3, 6), ADD, r(3, 4),
         ADDI, 2, 1, CMP, r(2, 0), JNZ, loop,
         HALT, 7]
code[8] = len(code)
code += [MOVI, 7, 1, HALT, 7]
print("/* generated by gen.py - spoiler */")
print("static const unsigned char bytecode[] = {" + ",".join("0x%02x" % b for b in code) + "};")
print("static const unsigned char vmdata[] = {" + ",".join("0x%02x" % b for b in data) + "};")
