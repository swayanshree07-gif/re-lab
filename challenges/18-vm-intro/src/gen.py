#!/usr/bin/env python3
"""Spoiler: generates bytecode.h for 18-vm-intro. Run: python3 gen.py > bytecode.h"""
import random
PW = b"st4ck_m4ch1ne"
PUSH, LOAD, XOR, ADD, SUB, EQ, AND, JZ, LEN, HALT, DUP, POP = range(1, 13)
rng = random.Random(18)
code = [LEN, PUSH, len(PW), EQ, JZ, 0xFF, PUSH, 1]  # JZ target patched below
order = list(range(len(PW))); rng.shuffle(order)       # check chars out of order
for i in order:
    k = rng.randrange(1, 256); op = (XOR, ADD, SUB)[i % 3]
    c = PW[i]
    v = c ^ k if op == XOR else (c + k) & 0xFF if op == ADD else (c - k) & 0xFF
    code += [LOAD, i, PUSH, k, op, PUSH, v, EQ, AND]
code += [HALT]
code[5] = len(code)
code += [PUSH, 0, HALT]
print("/* generated by gen.py - spoiler */")
print("static unsigned char bytecode[] = {" + ",".join("0x%02x" % b for b in code) + "};")
