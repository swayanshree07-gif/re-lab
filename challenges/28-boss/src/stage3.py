#!/usr/bin/env python3
"""SPOILER. Stage 3 model + generator (writes src/stage3.h, seeded).

Keygen stage: the "name" is the two earlier keys. H1 = fnv1a(stage-1 key),
H2 = fnv1a(stage-2 key) ^ 0x5732. The serial is "XXXXXXXX-XXXXXXXX" (upper
hex) = two 32-bit words (a, b). Four Feistel rounds
    L, R = R, L ^ F(R, rk[i]),   F(r, k) = rotl((r ^ k) * MUL, 9) + k
must turn (a, b) into (H1, H2). The model is written once with operators that
work on both z3 BitVecs and ints (rotl and the mask are passed in), so the
solver can check it without z3 and invert it as a fallback."""
import os, random
M = 0xFFFFFFFF
R = random.Random(0x5733)
RK = [R.getrandbits(32) for _ in range(4)]
MUL = R.getrandbits(32) | 1


def rotl_int(x, n):
    return ((x << n) | (x >> (32 - n))) & M


def F(r, k, rotl=rotl_int, mask=M):
    return (rotl((r ^ k) * MUL & mask, 9) + k) & mask


def forward(a, b, rotl=rotl_int, mask=M, rk=None):
    for k in (rk or RK):
        a, b = b, a ^ F(b, k, rotl, mask)
    return a, b


def inverse(h1, h2, rk=None):
    l, r = h1, h2
    for k in reversed(rk or RK):
        l, r = r ^ F(l, k), l
    return l, r


def fnv(data):
    h = 0x811C9DC5
    for c in data:
        h = ((h ^ c) * 0x01000193) & M
    return h


def target(key1, key2):
    return fnv(key1.encode()), fnv(key2.encode()) ^ 0x5732


def serial(key1, key2, rk=None):
    a, b = inverse(*target(key1, key2), rk=rk)
    return f"{a:08X}-{b:08X}"


if __name__ == "__main__":
    d = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(d, "stage3.h"), "w") as f:
        f.write("/* generated by src/stage3.py (SPOILER) */\n")
        f.write("static const unsigned int s3_rk[4] = {%s};\n" % ", ".join(f"0x{k:08X}u" for k in RK))
        f.write(f"#define S3_MUL 0x{MUL:08X}u\n")
    sp = open(os.path.join(d, "SPOILERS")).read().splitlines()
    sp = [l for l in sp if not l.startswith("stage 3")]
    k1 = sp[0].split(": ")[1]; k2 = sp[1].split(": ")[1]
    sp.append(f"stage 3 serial: {serial(k1, k2)}")
    open(os.path.join(d, "SPOILERS"), "w").write("\n".join(sp) + "\n")
