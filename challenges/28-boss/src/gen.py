#!/usr/bin/env python3
"""SPOILER. Writes src/stage1.h and src/SPOILERS (seeded, deterministic).
Stage 1: input bytes are read in permuted order perm[i], XORed with a
xorshift32 keystream (seeded by SEED mixed with the anti-debug salts, all 0
on a clean run) plus 13*i, and compared (no early exit) to ct[i]."""
import os, random
R = random.Random(0xB055)
PW = "b0ss_st4ge1_unl0ck"
SEED = 0x5EED1234 ^ R.getrandbits(32)
PERM = list(range(len(PW))); R.shuffle(PERM)


def mix(s, v):
    s = ((s ^ v) * 0x9E3779B1) & 0xFFFFFFFF
    return ((s << 13) | (s >> 19)) & 0xFFFFFFFF


def keystream(seed, salts, n):
    s = seed
    for v in salts:
        s = mix(s, v)
    out = []
    for i in range(n):
        s ^= (s << 13) & 0xFFFFFFFF; s ^= s >> 17; s ^= (s << 5) & 0xFFFFFFFF
        out.append((s + 13 * i) & 0xFF)
    return out


if __name__ == "__main__":
    d = os.path.dirname(os.path.abspath(__file__))
    ks = keystream(SEED, [0, 0, 0], len(PW))
    ct = [ord(PW[PERM[i]]) ^ ks[i] for i in range(len(PW))]
    with open(os.path.join(d, "stage1.h"), "w") as f:
        f.write("/* generated by gen.py */\n#define S1_LEN %d\n#define S1_SEED 0x%08Xu\n" % (len(PW), SEED))
        f.write("static const unsigned char s1_perm[S1_LEN] = { %s };\n" % ", ".join(map(str, PERM)))
        f.write("static const unsigned char s1_ct[S1_LEN] = { %s };\n" % ", ".join("0x%02x" % c for c in ct))
    open(os.path.join(d, "SPOILERS"), "w").write(f"stage 1 key: {PW}\n")
