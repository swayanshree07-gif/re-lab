#!/usr/bin/env python3
"""SPOILER. Writes src/vm_code.h and appends the stage-2 key to SPOILERS.
Program: CHK the length, then for each byte i:
  r0 = in[i]; r0 ^= x_i; r0 = rol(r0, s_i); r0 *= m_i (odd); r0 += r1; r1 = r0; CHK r0, e_i
so every check depends on all earlier bytes (chained through r1)."""
import os, random
import isa

R = random.Random(0x57A6E2)
PW = "v1rtu4l_m4ch1ne"


def build():
    prog = [("LEN", 2), ("CHK", 2, len(PW)), ("LDI", 1, R.getrandbits(8))]
    for i in range(len(PW)):
        prog += [("LDB", 0, i), ("XORI", 0, R.getrandbits(8)), ("ROLI", 0, R.randrange(1, 8)),
                 ("MULI", 0, R.randrange(1, 256, 2)), ("ADD", 0, 1), ("MOV", 1, 0), ("CHK", 0, 0)]
    prog.append(("HALT",))
    # fill in expected values by running the forward model
    r1 = prog[2][2]
    for i, c in enumerate(PW.encode()):
        base = 3 + 7 * i
        v = c ^ prog[base + 1][2]
        s = prog[base + 2][2]; v = ((v << s) | (v >> (8 - s))) & 0xFF
        v = (v * prog[base + 3][2]) & 0xFF
        v = (v + r1) & 0xFF; r1 = v
        prog[base + 6] = ("CHK", 0, v)
    return prog


if __name__ == "__main__":
    d = os.path.dirname(os.path.abspath(__file__))
    prog = build()
    code = isa.assemble(prog)
    ok, _ = isa.run(isa.disasm(code), PW.encode())
    assert ok and not isa.run(isa.disasm(code), b"x" * len(PW))[0]
    enc = isa.crypt(code)
    with open(os.path.join(d, "vm_code.h"), "w") as f:
        f.write("/* generated by gen2.py */\n#define BC_KEY 0x%02X\n" % isa.BC_KEY)
        for n, (op, _) in isa.OPS.items():
            f.write(f"#define OP_{n} 0x{op:02X}\n")
        f.write("static const unsigned char bc[%d] = {\n" % len(enc))
        for i in range(0, len(enc), 15):
            f.write("    " + ", ".join(f"0x{b:02x}" for b in enc[i:i + 15]) + ",\n")
        f.write("};\n")
    sp = os.path.join(d, "SPOILERS")
    lines = [l for l in open(sp).read().splitlines() if not l.startswith("stage 2 key:")]
    open(sp, "w").write("\n".join(lines + [f"stage 2 key: {PW}"]) + "\n")
