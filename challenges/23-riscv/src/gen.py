#!/usr/bin/env python3
"""Generate src/table.h from the password (spoiler!)."""
import os
PW = b"r15c_v_1s_0p3n"
h, out = 0x5a, []
for i, c in enumerate(PW):
    out.append(((c * 37 + h) ^ (i * 11 + 0x3c)) & 0xff)
    h = (h * 131 + c) & 0xffff
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "table.h")
with open(path, "w") as f:
    f.write("/* generated by gen.py */\n#define PW_LEN %d\n" % len(PW))
    f.write("static const unsigned char expected[PW_LEN] = {%s};\n" % ", ".join("0x%02x" % b for b in out))
