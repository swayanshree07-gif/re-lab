#!/usr/bin/env python3
"""Spoiler: generates bytecode.h for 20-vm-obf. Run: python3 gen.py > bytecode.h

Same register-VM semantics as 19, but:
  * opcode byte values are a random permutation: optab[enc] -> handler index
    (H_MOVI=0 .. H_HALT=16; every other optab entry -> 0xEE = invalid);
  * the program is encrypted: plain[pc] = blob[pc] ^ ks(pc),
    ks(pc) = (vmkey[pc & 3] + pc * 0x3b) & 0xff, decrypted on fetch.
Check: len 15; loop i: t = rol8((c + h) ^ (3*i), 5); err |= t ^ data[i]; h = h*13 ^ c (h0=0xa5)
"""
import random
PW = b"sh4ffl3d_0pc0d3"
NAMES = ["MOVI", "MOV", "LDI", "LDM", "ADD", "SUB", "XOR", "MUL", "ROL", "ADDI", "OR",
         "CMP", "JMP", "JZ", "JNZ", "LEN", "HALT"]
rng = random.Random(20)
vals = rng.sample(range(256), len(NAMES))
E = dict(zip(NAMES, vals))
optab = [0xEE] * 256
for i, v in enumerate(vals):
    optab[v] = i
KEY = [0x9c, 0x41, 0xd7, 0x2e]
H0, MULT, ROT, IM = 0xa5, 13, 5, 3

def rol8(x, n): return ((x << n) | (x >> (8 - n))) & 0xFF

data, h = [], H0
for i, c in enumerate(PW):
    data.append(rol8(((c + h) & 0xFF) ^ (IM * i & 0xFF), ROT)); h = ((h * MULT) ^ c) & 0xFF

def r(a, b): return (a << 4) | b
code = [E["LEN"], 0, E["MOVI"], 1, len(PW), E["CMP"], r(0, 1), E["JNZ"], None,
        E["MOVI"], 2, 0, E["MOVI"], 3, H0, E["MOVI"], 7, 0, E["MOVI"], 1, 0]
loop = len(code)  # r1 = 3*i
code += [E["LDI"], r(4, 2), E["MOV"], r(5, 4), E["ADD"], r(5, 3), E["XOR"], r(5, 1),
         E["ROL"], 5, ROT, E["MOV"], r(6, 2), E["LDM"], r(6, 6),
         E["XOR"], r(6, 5), E["OR"], r(7, 6),
         E["MOVI"], 6, MULT, E["MUL"], r(3, 6), E["XOR"], r(3, 4),
         E["ADDI"], 1, IM, E["ADDI"], 2, 1, E["CMP"], r(2, 0), E["JNZ"], loop, E["HALT"], 7]
code[8] = len(code)
code += [E["MOVI"], 7, 1, E["HALT"], 7]
blob = [b ^ ((KEY[pc & 3] + pc * 0x3b) & 0xFF) for pc, b in enumerate(code)]
hx = lambda a: ",".join("0x%02x" % b for b in a)
print("/* generated by gen.py - spoiler */")
print("static const unsigned char blob[] = {" + hx(blob) + "};")
print("static const unsigned char vmdata[] = {" + hx(data) + "};")
print("static const unsigned char optab[256] = {" + hx(optab) + "};")
print("static unsigned char vmkey[4] = {" + hx(KEY) + "};")
