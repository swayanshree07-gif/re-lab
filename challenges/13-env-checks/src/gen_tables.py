#!/usr/bin/env python3
"""SPOILER. Regenerates tables.h (encoded strings and passwords).
Run: python3 gen_tables.py > tables.h"""

def rotl8(x, r):
    return ((x << r) | (x >> (8 - r))) & 0xFF

# hidden strings: enc[i] = c ^ ((seed + 7*i) & 0xff), NUL included
STRINGS = [
    ("S_STATUS", "/proc/self/status", 0x5A),
    ("S_TRACER", "TracerPid:", 0x21),
    ("S_PROC", "/proc/", 0x77),
    ("S_COMM", "/comm", 0x3C),
    ("S_PRELOAD", "LD_PRELOAD=", 0x91),
    ("S_AUDIT", "LD_AUDIT=", 0xC4),
    # parent names, separated by '|'
    ("S_PARENTS", "gdb|gdbserver|strace|ltrace|lldb|lldb-server|r2|radare2|valgrind|frida", 0x0F),
]
PW_KEYS = (0x3D, 0xB2)          # [0] real, [1] decoy
PASSWORDS = ("3nv_l00ks_ok", "c4ught_y0u!!")

print("/* generated by gen_tables.py (SPOILER) */")
for name, s, seed in STRINGS:
    b = (s + "\0").encode()
    enc = [c ^ ((seed + 7 * i) & 0xFF) for i, c in enumerate(b)]
    print(f"#define {name}_SEED 0x{seed:02x}")
    print(f"#define {name}_LEN {len(b)}")
    print(f"static const unsigned char {name.lower()}[{len(b)}] = {{" + ", ".join(f"0x{x:02x}" for x in enc) + "};")
print(f"#define PW_LEN {len(PASSWORDS[0])}")
print("static const unsigned char pw_keys[2] = {" + ", ".join(f"0x{k:02x}" for k in PW_KEYS) + "};")
rows = []
for k, p in zip(PW_KEYS, PASSWORDS):
    assert len(p) == len(PASSWORDS[0])
    rows.append("{" + ", ".join(f"0x{rotl8(ord(c) ^ ((k + 11 * i) & 0xFF), 3):02x}" for i, c in enumerate(p)) + "}")
print(f"static const unsigned char pw_enc[2][PW_LEN] = {{ " + ",\n    ".join(rows) + " };")
