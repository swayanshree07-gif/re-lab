#!/usr/bin/env python3
"""Writes table.h for 26-signals (spoiler!). Deterministic (seeded).
Retries until every position has exactly one printable char that matches,
so a left-to-right brute force finds a unique password."""
import random, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from model import step, SEED

PW = b"s1gn4l_h4ndl3r"
rng = random.Random(26)
for _try in range(10000):
    kinds = [rng.randrange(3) for _ in PW]
    h, exp, ok = SEED, [], True
    for k, c in zip(kinds, PW):
        hits = [x for x in range(0x21, 0x7f) if (step(k, h, x) >> 8) & 0xffff == (step(k, h, c) >> 8) & 0xffff]
        if hits != [c]:
            ok = False; break
        h = step(k, h, c); exp.append((h >> 8) & 0xffff)
    if ok and len(set(kinds)) == 3:
        break
else:
    raise SystemExit("no table found")
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "table.h"), "w") as f:
    f.write("/* generated by gen.py */\n#define PW_LEN %d\n" % len(PW))
    f.write("static const unsigned char kinds[PW_LEN] = {%s};\n" % ", ".join(map(str, kinds)))
    f.write("static const unsigned short expect[PW_LEN] = {%s};\n" % ", ".join("0x%04x" % e for e in exp))
