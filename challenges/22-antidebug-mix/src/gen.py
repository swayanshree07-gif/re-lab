#!/usr/bin/env python3
"""SPOILER. Generates src/table.h: the password encrypted with the keystream
that a *clean* run derives (all anti-debug salts 0, code hash == expected)."""
import os
PW = b"m1x3d_s1gn4ls"
SEED = 0xC0FFEE17


def mix(s, v):
    s ^= v & 0xFFFFFFFF
    s = (s * 0x9E3779B1) & 0xFFFFFFFF
    return ((s << 13) | (s >> 19)) & 0xFFFFFFFF


def keystream(state, n):
    out = []
    for i in range(n):
        state ^= (state << 13) & 0xFFFFFFFF
        state ^= state >> 17
        state ^= (state << 5) & 0xFFFFFFFF
        out.append((state + 7 * i) & 0xFF)
    return out


def clean_state():
    s = SEED
    for _ in range(4):
        s = mix(s, 0)
    return s


if __name__ == "__main__":
    ks = keystream(clean_state(), len(PW))
    ct = [p ^ k for p, k in zip(PW, ks)]
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "table.h")
    with open(path, "w") as f:
        f.write("/* generated by gen.py */\n#define PW_LEN %d\n#define SEED 0x%08Xu\n" % (len(PW), SEED))
        f.write("static const unsigned char table[PW_LEN] = { %s };\n" % ", ".join("0x%02x" % c for c in ct))
